"""Search-latency benchmark over a synthetic 10K-thought corpus.

Targets NFR1 ``Search top-10 over 10K thoughts: under 100ms p95``.

The benchmark uses a deterministic stub embedder (so CI runs are reproducible
and free of model-load variance) and a synthetic corpus generated by
:func:`tests.fixtures.corpus.build_corpus` scaled to 10K entries.

Usage::

    uv run python -m bench.search_10k --size 10000 --queries 100

Exits non-zero if the measured p95 exceeds the configured threshold.
"""

from __future__ import annotations

import argparse
import logging
import statistics
import sys
import tempfile
import time
from pathlib import Path

from tests.fixtures.corpus import build_corpus, write_corpus_to_vault

from engram.storage.facade import VaultStorage

_log = logging.getLogger("bench.search_10k")

_DIM = 32
_DEFAULT_SIZE = 10_000
_DEFAULT_QUERIES = 100
_TARGET_P95_MS = 100.0


class _DeterministicEmbedder:
    """Cheap deterministic embedder so the benchmark isolates SQLite ANN latency.

    Uses a simple hash-based projection into 32 dims. Not semantically
    meaningful - we are measuring vector-search latency, not retrieval
    quality.
    """

    @property
    def model_name(self) -> str:
        return "bench-stub"

    @property
    def dimension(self) -> int:
        return _DIM

    def embed(self, text: str) -> list[float]:
        v = [0.0] * _DIM
        for i, ch in enumerate(text):
            v[(ord(ch) + i) % _DIM] += 1.0
        norm = sum(component * component for component in v) ** 0.5 or 1.0
        return [component / norm for component in v]

    async def aembed(self, text: str) -> list[float]:
        return self.embed(text)


def _percentile(samples: list[float], pct: float) -> float:
    if not samples:
        return 0.0
    ordered = sorted(samples)
    rank = max(0, min(len(ordered) - 1, round(pct / 100.0 * (len(ordered) - 1))))
    return ordered[rank]


def run_benchmark(
    size: int,
    queries: int,
    *,
    target_p95_ms: float = _TARGET_P95_MS,
) -> int:
    """Build a synthetic vault, run ``queries`` searches, report timings.

    Returns the exit code: 0 on pass, 1 if p95 exceeds ``target_p95_ms``.
    """
    embedder = _DeterministicEmbedder()

    with tempfile.TemporaryDirectory(prefix="engram-bench-") as tmp:
        tmp_path = Path(tmp)
        storage = VaultStorage(
            thoughts_dir=tmp_path / "thoughts",
            index_db_path=tmp_path / ".indexes" / "engram.db",
            embedding_dim=_DIM,
        )
        try:
            _log.info("building synthetic %d-thought corpus...", size)
            t0 = time.perf_counter()
            corpus = build_corpus(size=size, seed_label=f"bench-{size}")
            write_corpus_to_vault(storage, corpus, embedder=embedder)
            build_seconds = time.perf_counter() - t0
            _log.info("corpus capture finished in %.2fs", build_seconds)

            # Warmup: a few queries so the SQLite page cache is hot.
            warmup_texts = [c.content for c in corpus[:5]]
            for text in warmup_texts:
                storage.search(query_embedding=embedder.embed(text), k=10)

            durations_ms: list[float] = []
            for i in range(queries):
                query_text = corpus[i % len(corpus)].content
                query_vec = embedder.embed(query_text)
                start = time.perf_counter()
                storage.search(query_embedding=query_vec, k=10)
                durations_ms.append((time.perf_counter() - start) * 1000.0)
        finally:
            storage.close()

    p50 = _percentile(durations_ms, 50)
    p95 = _percentile(durations_ms, 95)
    p99 = _percentile(durations_ms, 99)
    mean = statistics.fmean(durations_ms)

    print(
        f"\nsearch_10k benchmark (size={size}, queries={queries})\n"
        f"  capture phase:  {build_seconds:6.2f}s\n"
        f"  search latency: mean={mean:6.2f}ms  p50={p50:6.2f}ms  "
        f"p95={p95:6.2f}ms  p99={p99:6.2f}ms\n"
        f"  NFR1 target:    p95 < {target_p95_ms:.0f}ms\n"
        f"  result:         {'PASS' if p95 <= target_p95_ms else 'FAIL'}\n"
    )

    return 0 if p95 <= target_p95_ms else 1


def main(argv: list[str] | None = None) -> int:
    """Entrypoint for ``python -m bench.search_10k``."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--size", type=int, default=_DEFAULT_SIZE)
    parser.add_argument("--queries", type=int, default=_DEFAULT_QUERIES)
    parser.add_argument(
        "--target-p95-ms",
        type=float,
        default=_TARGET_P95_MS,
        help="Fail-the-build threshold for search p95 (default: 100ms per NFR1).",
    )
    parser.add_argument("--verbose", "-v", action="store_true")
    args = parser.parse_args(argv)

    logging.basicConfig(
        level=logging.INFO if args.verbose else logging.WARNING,
        format="%(message)s",
    )
    return run_benchmark(args.size, args.queries, target_p95_ms=args.target_p95_ms)


if __name__ == "__main__":
    sys.exit(main())
